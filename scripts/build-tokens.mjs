// tokens.json -> tokens.css. `npm run tokens` writes src/styles/tokens.css; `npm run tokens:check` (run in CI)
// fails when tokens.css does not match tokens.json, so nobody can hand-edit one without the other.
// tokens.json itself comes from Figma: see scripts/figma/export-tokens.js.
import { readFileSync, writeFileSync } from 'node:fs';

const JSON_FILE = new URL('../src/styles/tokens.json', import.meta.url);
const CSS_FILE = new URL('../src/styles/tokens.css', import.meta.url);
const tokens = JSON.parse(readFileSync(JSON_FILE, 'utf8'));

// The view modes only change a few colours. Each gets a light rule, an explicit dark rule and a system-dark rule.
const VIEWS = {
  engineer: 'Engineer view: Dev Mode green replaces the annotation blue',
  recruiter: 'Recruiter view: violet replaces the annotation blue',
};

// Walk the tree and collect every token as { path, token }.
const all = [];
const walk = (node, path) => {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (val.$type) all.push({ path: [...path, key], token: val });
    else walk(val, [...path, key]);
  }
};
walk(tokens, []);
const byRef = Object.fromEntries(all.map(({ path, token }) => [path.join('.'), token]));
const of = (type) => all.filter(({ token }) => token.$type === type);
const cssName = (path) => `--${path.join('-')}`;

// Colours: hex when solid, rgba() with the hex channels when transparent. References follow the same mode.
const modeValue = (token, mode) => (mode && token.$extensions?.['com.rockgomes.modes']?.[mode]) || token.$value;
const resolve = (val, mode) => {
  const fallback = mode?.endsWith('-dark') ? 'dark' : null;
  while (typeof val === 'string') {
    const target = byRef[val.slice(1, -1)];
    val = target.$extensions?.['com.rockgomes.modes']?.[mode] ?? target.$extensions?.['com.rockgomes.modes']?.[fallback] ?? target.$value;
  }
  return val;
};
const colorCss = (c) => {
  if (c.alpha === 1) return c.hex;
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(c.hex.slice(i, i + 2), 16));
  return `rgba(${r}, ${g}, ${b}, ${c.alpha})`;
};
const colorValue = (token, mode) => colorCss(resolve(modeValue(token, mode), mode));

const colors = of('color');
const decls = (list, indent) => list.map(([name, value]) => `${indent}${name}: ${value};`).join('\n');
const colorDecls = (mode, onlyChanged, indent = '  ') => {
  const base = mode?.endsWith('-dark') ? 'dark' : null;
  return decls(
    colors
      .map(({ path, token }) => [cssName(path), colorValue(token, mode), colorValue(token, base)])
      .filter(([, value, baseValue]) => !onlyChanged || value !== baseValue),
    indent,
  );
};

// Type: `weight size / line-height family`. Fluid sizes (clamp) come from the Figma text style description.
const px0 = (v) => (v === '0px' ? '0' : v);
const fontList = (list) => list.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ');
const typography = of('typography').map(({ path, token }) => {
  const v = token.$value;
  const size = token.$extensions?.['com.rockgomes.fluid'] ?? v.fontSize;
  return { name: path.slice(1).join('-'), font: `${v.fontWeight} ${size} / ${v.lineHeight} var(--${v.fontFamily.slice(1, -1).replace('.', '-')})`, tracking: v.letterSpacing };
});
const shadow = (list) => list.map((s) => [s.offsetX, s.offsetY, s.blur, s.spread].filter((x, i) => i < 3 || x !== '0px').map(px0).join(' ') + ` ${colorCss(s.color)}`).join(', ');

const css = `/* Design tokens. Made from tokens.json by scripts/build-tokens.mjs (npm run tokens). tokens.json is exported
   from the tokens variable collection in Figma (scripts/figma/export-tokens.js).
   Light = "Light - Crisp" mode, Dark = "Dark" mode.
   Engineer view = "Light - Dev" and "Dark - Dev" modes.
   Recruiter view = "Light - Recruiter" and "Dark - Recruiter" modes.
   Do not edit this file by hand: change Figma, re-export tokens.json, then run npm run tokens. */
:root {
${colorDecls(null, false)}
  color-scheme: light;
}

:root[data-theme="dark"] {
${colorDecls('dark', false)}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorDecls('dark', false, '    ')}
    color-scheme: dark;
  }
}
${Object.entries(VIEWS).map(([view, comment]) => `
/* ${comment} */
:root[data-view="${view}"]:not([data-theme="dark"]) {
${colorDecls(view, true)}
}
:root[data-view="${view}"][data-theme="dark"] {
${colorDecls(`${view}-dark`, true)}
}
@media (prefers-color-scheme: dark) {
  :root[data-view="${view}"]:not([data-theme="light"]) {
${colorDecls(`${view}-dark`, true, '    ')}
  }
}
`).join('')}
/* Space and radius (Figma number variables) */
:root {
${decls(of('dimension').map(({ path, token }) => [cssName(path), token.$value]), '  ')}
}

/* Type (Figma text styles) */
:root {
${decls(of('fontFamily').map(({ path, token }) => [cssName(path), fontList(token.$value)]), '  ')}

${decls(typography.map((t) => [`--type-${t.name}`, t.font]), '  ')}

${decls(typography.filter((t) => t.tracking !== '0em').map((t) => [`--tracking-${t.name}`, t.tracking]), '  ')}

  /* Effects (Figma effect styles) */
${decls(of('shadow').map(({ path, token }) => [cssName(path), shadow(token.$value)]), '  ')}
}
`;

if (process.argv.includes('--check')) {
  if (readFileSync(CSS_FILE, 'utf8') !== css) {
    console.error('src/styles/tokens.css does not match src/styles/tokens.json. Run `npm run tokens` and commit the result.');
    process.exit(1);
  }
  console.log('tokens.css matches tokens.json');
} else {
  writeFileSync(CSS_FILE, css);
  console.log('Wrote src/styles/tokens.css');
}
